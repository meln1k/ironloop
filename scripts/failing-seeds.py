#!/usr/bin/env python3
"""Writes crates/ironloop-sim/FAILING_SEEDS.md from a DST sweep.

Usage: scripts/failing-seeds.py [seeds] [start] [--from FILE]
       (default 4000 seeds from 0; --from reads the output of
       `dst --seeds N --start S --list-failures` instead of running it)

Runs `dst --list-failures` over the seeds and lists every failing seed by
property, so the document is complete for the range it names. Seed numbers
are only meaningful for the commit it records: regenerate it after changing
the scenario generator, the simulator, or the firmware.
"""

import os
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = "crates/ironloop-sim/FAILING_SEEDS.md"


def main():
    os.chdir(ROOT)
    args = sys.argv[1:]
    saved = args.pop(args.index("--from") + 1) if "--from" in args else None
    args = [a for a in args if a != "--from"]
    n = int(args[0]) if args else 4000
    start = int(args[1]) if len(args) > 1 else 0
    if saved:
        out = open(saved).read()
    else:
        # One long sweep: the dst profile's slower link pays for itself.
        subprocess.run(["cargo", "build", "-q", "--profile", "dst", "-p", "ironloop-sim", "--bin", "dst"], check=True)
        out = subprocess.run(
            ["./target/dst/dst", "--seeds", str(n), "--start", str(start), "--list-failures"],
            capture_output=True,
            text=True,
        ).stdout
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "--", "crates"], capture_output=True, text=True).stdout.strip()

    by_prop = {}
    for line in out.splitlines():
        if not line.startswith("failure "):
            continue
        # failure <seed> <property> <t_us> [<workload>] <detail>
        _, seed, prop, t_us, rest = line.split(" ", 4)
        workload, _, detail = rest[1:].partition("] ")
        by_prop.setdefault(prop, []).append((int(seed), int(t_us), detail, workload))
    notes = [l.strip() for l in out.splitlines() if l.startswith("  FAIL  deterministic_replay") or l.startswith("  THIN  ")]

    lines = [
        "# Failing seeds",
        "",
        f"Every seed in {start}–{start + n - 1} ({n} seeds) that fails a property, generated by "
        f"`scripts/failing-seeds.py {n} {start}` on commit {commit}{' with uncommitted changes' if dirty else ''}. "
        "Replay one with `cargo run --release -p ironloop-sim --bin dst -- --seed N --trace`. "
        "The seeds are only valid for that commit: regenerate this file after changing the generator, the simulator, or the firmware.",
        "",
    ]
    lines += [f"Sweep warnings: {', '.join(notes)}", ""] if notes else []
    if not by_prop:
        lines.append("No seed fails.")
    else:
        lines += ["| Property | Seeds failing |", "| --- | --- |"]
        for prop, fails in sorted(by_prop.items(), key=lambda kv: -len(kv[1])):
            lines.append(f"| `{prop}` | {len(fails)} |")
        for prop, fails in sorted(by_prop.items(), key=lambda kv: -len(kv[1])):
            lines += ["", f"## `{prop}` ({len(fails)})", "", "| Seed | At | Detail | Workload |", "| --- | --- | --- | --- |"]
            for seed, t_us, detail, workload in sorted(fails):
                lines.append(f"| {seed} | {t_us / 1e6:.3f} s | {detail.replace('|', '/')} | {workload} |")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {sum(map(len, by_prop.values()))} failures in {len({s for v in by_prop.values() for s, *_ in v})} seeds")


if __name__ == "__main__":
    main()
